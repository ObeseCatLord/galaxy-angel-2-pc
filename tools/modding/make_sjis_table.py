#!/usr/bin/env python3
"""Generate ps2xRuntime/include/runtime/ga2_sjis_table.h: the Unicode value
of every double-byte Shift-JIS code (lead 0x81-0x9F and 0xE0-0xFC, trail
0x40-0xFC) by Windows code page 932, which the sharp-text feature
(ga2_hitext) uses to find a character in the vector font. 0 = no character.

  make_sjis_table.py <out.h>

Standard library only."""

import sys

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = 0xFD - 0x40


def main() -> None:
    out = sys.argv[1]
    rows = []
    for lead in LEADS:
        row = []
        for trail in range(0x40, 0xFD):
            value = 0
            if trail != 0x7F:
                try:
                    text = bytes([lead, trail]).decode("cp932")
                    if len(text) == 1 and not 0xE000 <= ord(text) <= 0xF8FF:
                        value = ord(text)
                except UnicodeDecodeError:
                    pass
            row.append(value)
        rows.append(row)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/modding/make_sjis_table.py (do not edit): Unicode\n"
                "// (code page 932) of each double-byte Shift-JIS code, 0 = none.\n"
                "// Row = lead byte (0x81-0x9F, then 0xE0-0xFC), column = trail byte - 0x40.\n"
                "#pragma once\n\n#include <cstdint>\n\nnamespace ga2_hitext\n{\n"
                f"    inline constexpr unsigned kSjisLeads = {len(LEADS)}, kSjisTrails = {TRAILS};\n"
                "    inline constexpr uint16_t kSjisToUnicode[kSjisLeads * kSjisTrails] = {\n")
        for row in rows:
            f.write("        " + ",".join(f"0x{v:04x}" for v in row) + ",\n")
        f.write("    };\n}\n")


if __name__ == "__main__":
    main()
